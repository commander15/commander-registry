import os
import sys
import json
from datetime import datetime, timezone
from jsonschema import validate, ValidationError

def sanitize_pattern(pattern_str):
    """
    Automatically fixes common regex issues generated by third-party tools,
    such as invalid backward character ranges (e.g., `_-` where ASCII '_' is 95 and '-' is 45).
    """
    if "_-" in pattern_str:
        pattern_str = pattern_str.replace("_-", "_\\-")
    return pattern_str

def sanitize_schema(node):
    """Recursively traverse a JSON schema object and sanitize all 'pattern' values."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "pattern" and isinstance(value, str):
                node[key] = sanitize_pattern(value)
            else:
                sanitize_schema(value)
    elif isinstance(node, list):
        for item in node:
            sanitize_schema(item)
    return node

def load_schema(schema_path):
    if not os.path.isfile(schema_path):
        print(f"Error: Schema file not found at '{schema_path}'.")
        sys.exit(1)
    try:
        with open(schema_path, "r", encoding="utf-8") as f:
            schema = json.load(f)
        # Sanitize regex patterns dynamically in memory after loading
        return sanitize_schema(schema)
    except Exception as e:
        print(f"Error parsing schema file {schema_path}: {e}")
        sys.exit(1)

def main():
    packages_dir = "packages"
    schemas_dir = "schemas"
    index_file = "index.json"
    
    # Load JSON schemas including the registry index schema
    meta_schema_path = os.path.join(schemas_dir, "package_meta.json")
    version_schema_path = os.path.join(schemas_dir, "package_version.json")
    index_schema_path = os.path.join(schemas_dir, "registry_index.json")
    
    meta_schema = load_schema(meta_schema_path)
    version_schema = load_schema(version_schema_path)
    index_schema = load_schema(index_schema_path)

    index_data = {
        "registry_version": 1,
        "updated_at": datetime.now(timezone.utc).isoformat(),
        "packages": {}
    }

    if not os.path.isdir(packages_dir):
        print(f"Error: '{packages_dir}' directory not found.")
        sys.exit(1)

    # Iterate through package directories (e.g., datagate, jsoner, qeloquent, restlink, widgetry)
    for pkg_name in sorted(os.listdir(packages_dir)):
        pkg_path = os.path.join(packages_dir, pkg_name)
        if not os.path.isdir(pkg_path):
            continue

        meta_file = os.path.join(pkg_path, "meta.json")
        if not os.path.isfile(meta_file):
            print(f"Warning: Skipping package '{pkg_name}' — missing meta.json")
            continue

        # Load and validate package metadata (skip entire package on failure)
        try:
            with open(meta_file, "r", encoding="utf-8") as f:
                meta = json.load(f)
            validate(instance=meta, schema=meta_schema)
        except ValidationError as e:
            print(f"Warning: Skipping package '{pkg_name}' due to meta.json validation error:\n  -> {e.message}")
            continue
        except Exception as e:
            print(f"Error parsing {meta_file}: {e}")
            continue

        # Discover and validate all version json files (skip individual invalid versions)
        versions = []
        for filename in sorted(os.listdir(pkg_path)):
            if filename.endswith(".json") and filename != "meta.json":
                version_file_path = os.path.join(pkg_path, filename)
                
                try:
                    with open(version_file_path, "r", encoding="utf-8") as vf:
                        version_data = json.load(vf)
                    validate(instance=version_data, schema=version_schema)
                except ValidationError as e:
                    print(f"Warning: Skipping version file '{pkg_name}/{filename}' due to schema validation error:\n  -> {e.message}")
                    continue
                except Exception as e:
                    print(f"Error parsing version file {version_file_path}: {e}")
                    continue

                version_str = filename[:-5]  # Strip '.json'
                if version_str.startswith('v'):
                    version_str = version_str.removeprefix('v')
                versions.append(version_str)

        if not versions:
            print(f"Warning: Package '{pkg_name}' has no valid version manifests; skipping package.")
            continue

        # Sort versions (latest/highest version first)
        versions.sort(key=lambda s: [int(u) if u.isdigit() else u for u in s.replace('-', '.').split('.')])
        versions.reverse()
        
        latest_version = versions[0]

        # Register package in index
        index_data["packages"][pkg_name] = {
            "display_name": meta.get("display_name", pkg_name.capitalize()),
            "description": meta.get("description", ""),
            "latest": latest_version,
            "versions": versions
        }

    # Validate the final generated index structure against registry_index.json schema
    try:
        validate(instance=index_data, schema=index_schema)
    except ValidationError as e:
        print(f"Critical Error: Generated index.json failed schema validation:\n  -> {e.message}")
        sys.exit(1)

    # Write out index.json
    try:
        with open(index_file, "w", encoding="utf-8") as f:
            json.dump(index_data, f, indent=2)
        print(f"Successfully generated and validated {index_file} with {len(index_data['packages'])} packages.")
    except Exception as e:
        print(f"Error writing {index_file}: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()